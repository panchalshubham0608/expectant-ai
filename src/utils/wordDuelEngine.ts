export const sanitizeFiveLetterWord = (raw: string): string =>
  raw.toUpperCase().replace(/[^A-Z]/g, '').slice(0, WORD_LENGTH);

export const isValidFiveLetterInput = (word: string): boolean =>
  /^[A-Z]{5}$/.test(word);

export const pickRandomWord = (excludeWords: ReadonlySet<string> = new Set()): string => {
  const pool = CURATED_FIVE_LETTER_WORDS.filter((w) => !excludeWords.has(w));
  const source = pool.length > 0 ? pool : CURATED_FIVE_LETTER_WORDS;
  return source[Math.floor(Math.random() * source.length)];
};

export const pickSetterSuggestions = (count = 4, excludeWords: ReadonlySet<string> = new Set()): string[] => {
  const pool = CURATED_FIVE_LETTER_WORDS.filter((w) => !excludeWords.has(w));
  const copy = [...(pool.length >= count ? pool : CURATED_FIVE_LETTER_WORDS)];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const tmp = copy[i];
    copy[i] = copy[j];
    copy[j] = tmp;
  }
  return copy.slice(0, count);
};

/**
 * Exact two-pass Wordle evaluation handling duplicate letters accurately.
 */
export const evaluateWordGuess = (guess: string, target: string): LetterEval[] => {
  const result: LetterEval[] = Array.from({ length: WORD_LENGTH }, () => 'absent');
  const remainingCounts: Record<string, number> = {};

  for (let i = 0; i < WORD_LENGTH; i++) {
    const tChar = target[i];
    if (guess[i] === tChar) {
      result[i] = 'correct';
    } else {
      remainingCounts[tChar] = (remainingCounts[tChar] ?? 0) + 1;
    }
  }

  for (let i = 0; i < WORD_LENGTH; i++) {
    if (result[i] === 'correct') continue;
    const gChar = guess[i];
    const count = remainingCounts[gChar] ?? 0;
    if (count > 0) {
      result[i] = 'present';
      remainingCounts[gChar] = count - 1;
    }
  }

  return result;
};

const EVAL_PRIORITY: Record<LetterEval, number> = {
  absent: 1,
  present: 2,
  correct: 3,
};

export const computeKeyboardStates = (
  guesses: readonly string[],
  target: string
): Record<string, LetterEval> => {
  const states: Record<string, LetterEval> = {};
  for (const guess of guesses) {
    const evals = evaluateWordGuess(guess, target);
    for (let i = 0; i < WORD_LENGTH; i++) {
      const ch = guess[i];
      const ev = evals[i];
      const existing = states[ch];
      if (!existing || EVAL_PRIORITY[ev] > EVAL_PRIORITY[existing]) {
        states[ch] = ev;
      }
    }
  }
  return states;
};
