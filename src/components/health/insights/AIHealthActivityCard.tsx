import { useCallback, useEffect, useRef, useState } from 'react';
import {
  Sparkles,
  RefreshCw,
  Loader2,
  CheckCircle2,
  Footprints,
  Clock,
  ShieldAlert,
  ChevronDown,
  ChevronUp,
  HeartPulse,
  ArrowRight,
} from 'lucide-react';
import { useAuth } from '../../../hooks/useAuth';
import type { DailyLog } from '../../../models/dailylLog';
import type {
  ActivityStatusLevel,
  AIHealthActivityInsight,
} from '../../../models/health';
import type { Measurement } from '../../../models/measurement';
import type { Medication } from '../../../models/medication';
import type { ExpectantProfile } from '../../../models/profile';
import {
  generateHealthActivityInsight,
  saveHealthActivityInsight,
  subscribeToLatestHealthActivityInsight,
} from '../../../services/ai/healthInsightsService';
import { subscribeToRecentDailyLogs } from '../../../services/ai/journalChatPersistence';
import { subscribeToMedications } from '../../../services/medication/medicationService';
import { getGeminiApiKey } from '../../../services/profiles/profileService';

interface AIHealthActivityCardProps {
  profileId: string;
  profile: ExpectantProfile | null;
  measurements: Measurement[];
}

const getStatusBadgeClasses = (status: ActivityStatusLevel): string => {
  switch (status) {
    case 'optimal':
      return 'bg-emerald-50 text-emerald-700 ring-emerald-600/20';
    case 'steady':
      return 'bg-purple-50 text-purple-700 ring-purple-600/20';
    case 'gentle-needed':
      return 'bg-amber-50 text-amber-700 ring-amber-600/20';
    case 'rest-focused':
      return 'bg-sky-50 text-sky-700 ring-sky-600/20';
    default:
      return 'bg-purple-50 text-purple-700 ring-purple-600/20';
  }
};

const toLocalDateKey = (date = new Date()): string => {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

export default function AIHealthActivityCard({
  profileId,
  profile,
  measurements,
}: AIHealthActivityCardProps) {
  const { user } = useAuth();
  const [insight, setInsight] = useState<AIHealthActivityInsight | null>(null);
  const [recentLogs, setRecentLogs] = useState<DailyLog[]>([]);
  const [medications, setMedications] = useState<Medication[]>([]);
  const [isLoadingInsight, setIsLoadingInsight] = useState(true);
  const [isLogsLoaded, setIsLogsLoaded] = useState(false);
  const [isGenerating, setIsGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [isExpanded, setIsExpanded] = useState(true);

  const autoGeneratedForDateRef = useRef<string | null>(null);

  useEffect(() => {
    if (!user?.uid || !profileId) {
      setIsLoadingInsight(false);
      return;
    }

    const unsubInsight = subscribeToLatestHealthActivityInsight(
      user.uid,
      profileId,
      (latest) => {
        setInsight(latest);
        setIsLoadingInsight(false);
      },
      () => {
        setIsLoadingInsight(false);
      },
    );

    const unsubLogs = subscribeToRecentDailyLogs(
      user.uid,
      profileId,
      (logs) => {
        setRecentLogs(logs);
        setIsLogsLoaded(true);
      },
      7,
    );

    const unsubMeds = subscribeToMedications(
      user.uid,
      profileId,
      (meds) => {
        setMedications(meds);
      },
      () => undefined,
    );

    return () => {
      unsubInsight();
      unsubLogs();
      unsubMeds();
    };
  }, [user?.uid, profileId]);

  const handleGenerateInsight = useCallback(
    async (e?: React.MouseEvent) => {
      if (e) e.stopPropagation();
      if (!user?.uid || !profile || isGenerating) return;

      setIsGenerating(true);
      setError(null);

      try {
        const userApiKey = await getGeminiApiKey(user.uid, profileId).catch(
          () => undefined,
        );
        const generated = await generateHealthActivityInsight(
          {
            profile,
            recentDailyLogs: recentLogs,
            measurements,
            medications,
          },
          userApiKey || undefined,
        );

        await saveHealthActivityInsight(user.uid, profileId, generated);
        setInsight(generated);
      } catch (err) {
        const msg =
          err instanceof Error
            ? err.message
            : 'Unable to generate Gemini health insights right now.';
        setError(msg);
      } finally {
        setIsGenerating(false);
      }
    },
    [user?.uid, profile, profileId, recentLogs, measurements, medications, isGenerating],
  );

  // Auto-generate today's insight once if missing or from a previous day
  useEffect(() => {
    const todayKey = toLocalDateKey();
    if (
      !user?.uid ||
      !profile ||
      isLoadingInsight ||
      !isLogsLoaded ||
      isGenerating
    ) {
      return;
    }

    if (insight && insight.date === todayKey) {
      return;
    }

    if (autoGeneratedForDateRef.current === todayKey) {
      return;
    }

    autoGeneratedForDateRef.current = todayKey;
    void handleGenerateInsight();
  }, [
    user?.uid,
    profile,
    isLoadingInsight,
    isLogsLoaded,
    isGenerating,
    insight,
    handleGenerateInsight,
  ]);

  const todayKey = toLocalDateKey();
  const todayLog = recentLogs.find((l) => l.date === todayKey);
  const manualStepsToday = (todayLog?.activities ?? [])
    .filter((a) => a.source !== 'google_health')
    .reduce((acc, a) => acc + (a.steps ?? 0), 0);
  const manualMinsToday = (todayLog?.activities ?? [])
    .filter((a) => a.source !== 'google_health')
    .reduce((acc, a) => acc + (a.durationMinutes ?? 0), 0);

  const stepsToday = (todayLog?.activitySummary?.steps ?? 0) + manualStepsToday;
  const activeMinutesToday =
    (todayLog?.activitySummary?.activeMinutes ?? 0) + manualMinsToday;

  return (
    <div className="relative overflow-hidden rounded-[2rem] bg-gradient-to-br from-purple-50/90 via-white to-fuchsia-50/70 p-6 shadow-sm ring-1 ring-purple-100">
      {/* Subtle decorative glow */}
      <div className="pointer-events-none absolute -right-10 -top-10 h-36 w-36 rounded-full bg-fuchsia-200/30 blur-3xl" />

      {/* Header */}
      <div
        className="relative z-10 flex cursor-pointer select-none flex-wrap items-center justify-between gap-3"
        onClick={() => setIsExpanded(!isExpanded)}
      >
        <div className="flex items-center gap-3">
          <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-2xl bg-gradient-to-br from-purple-600 to-fuchsia-600 text-white shadow-sm">
            <Sparkles size={18} />
          </div>
          <div>
            <div className="flex flex-wrap items-center gap-2">
              <h3 className="text-lg font-bold text-gray-900">
                Gemini Health &amp; Activity Coach
              </h3>
              {insight && (
                <span
                  className={`inline-flex items-center rounded-full px-2.5 py-0.5 text-[11px] font-semibold ring-1 ring-inset ${getStatusBadgeClasses(
                    insight.activityStatus,
                  )}`}
                >
                  {insight.activityStatusLabel}
                </span>
              )}
            </div>
            <p className="text-xs text-gray-500">
              {insight
                ? `Tailored to Week ${insight.pregnancyWeek} (${insight.trimester})`
                : 'Personalized to your pregnancy profile, vitals & activity'}
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={handleGenerateInsight}
            disabled={isGenerating || !profile}
            className="inline-flex items-center gap-1.5 rounded-full bg-white px-3 py-1.5 text-xs font-semibold text-purple-700 shadow-2xs ring-1 ring-purple-200/80 transition hover:bg-purple-50 disabled:opacity-50"
            title="Regenerate Gemini health insights"
          >
            <RefreshCw size={13} className={isGenerating ? 'animate-spin' : ''} />
            <span>{isGenerating ? 'Analyzing…' : 'Refresh AI'}</span>
          </button>

          {isExpanded ? (
            <ChevronUp size={20} className="text-slate-400" />
          ) : (
            <ChevronDown size={20} className="text-slate-400" />
          )}
        </div>
      </div>

      {/* Collapsed Quick Summary */}
      {!isExpanded && insight && (
        <div className="relative z-10 mt-3 flex flex-wrap items-center justify-between gap-2 text-xs text-gray-600">
          <span className="font-medium text-gray-800">
            {insight.emoji} {insight.headline}
          </span>
          <div className="flex items-center gap-2">
            <span className="rounded-full bg-white px-2.5 py-1 font-semibold text-purple-700 ring-1 ring-purple-100">
              Activity Score: {insight.activityScore}/100
            </span>
            <span className="rounded-full bg-white px-2.5 py-1 font-semibold text-emerald-700 ring-1 ring-emerald-100">
              Goal: {insight.recommendedDailySteps.toLocaleString()} steps
            </span>
          </div>
        </div>
      )}

      {/* Expanded Body */}
      {isExpanded && (
        <div className="relative z-10 mt-5 space-y-4">
          {error && (
            <div className="rounded-2xl border border-red-100 bg-red-50 px-4 py-3 text-xs text-red-700">
              {error}
            </div>
          )}

          {(isLoadingInsight || isGenerating) && !insight ? (
            <div className="flex items-center justify-center gap-2.5 py-8 text-sm text-gray-500">
              <Loader2 className="animate-spin text-purple-600" size={20} />
              <span>
                Analyzing your physical activity and vitals for your pregnancy stage…
              </span>
            </div>
          ) : insight ? (
            <>
              {/* Headline & Summary Banner */}
              <div className="rounded-2xl bg-white/90 p-4 shadow-2xs ring-1 ring-purple-100/80">
                <div className="flex items-start gap-3">
                  <div className="flex h-11 w-11 shrink-0 items-center justify-center rounded-2xl bg-purple-50 text-2xl">
                    {insight.emoji || '🌿'}
                  </div>
                  <div className="min-w-0 flex-1">
                    <h4 className="text-base font-bold text-gray-900">
                      {insight.headline}
                    </h4>
                    <p className="mt-1 text-sm leading-relaxed text-gray-600">
                      {insight.summary}
                    </p>
                    {insight.weeklyProgressNote && (
                      <p className="mt-2 text-xs font-medium text-purple-700">
                        {insight.weeklyProgressNote}
                      </p>
                    )}
                  </div>
                </div>
              </div>

              {/* Scores & Profile-Relative Daily Targets Grid */}
              <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
                <div className="rounded-2xl bg-white/90 p-3.5 ring-1 ring-purple-100/70">
                  <div className="flex items-center gap-1.5 text-xs font-semibold text-purple-700">
                    <Footprints size={14} />
                    <span>Activity Score</span>
                  </div>
                  <div className="mt-1 flex items-baseline gap-1">
                    <span className="text-2xl font-bold text-gray-900">
                      {insight.activityScore}
                    </span>
                    <span className="text-xs font-medium text-gray-400">/100</span>
                  </div>
                  <p className="mt-0.5 text-[11px] text-gray-500">
                    Stage-adjusted rhythm
                  </p>
                </div>

                <div className="rounded-2xl bg-white/90 p-3.5 ring-1 ring-fuchsia-100/70">
                  <div className="flex items-center gap-1.5 text-xs font-semibold text-fuchsia-700">
                    <HeartPulse size={14} />
                    <span>Wellness Score</span>
                  </div>
                  <div className="mt-1 flex items-baseline gap-1">
                    <span className="text-2xl font-bold text-gray-900">
                      {insight.overallScore}
                    </span>
                    <span className="text-xs font-medium text-gray-400">/100</span>
                  </div>
                  <p className="mt-0.5 text-[11px] text-gray-500">
                    Activity &amp; vitals
                  </p>
                </div>

                <div className="rounded-2xl bg-white/90 p-3.5 ring-1 ring-emerald-100/70">
                  <div className="flex items-center gap-1.5 text-xs font-semibold text-emerald-700">
                    <Footprints size={14} />
                    <span>AI Step Target</span>
                  </div>
                  <div className="mt-1 flex items-baseline gap-1">
                    <span className="text-lg font-bold text-gray-900">
                      {insight.recommendedDailySteps.toLocaleString()}
                    </span>
                    <span className="text-[11px] text-gray-400">/day</span>
                  </div>
                  <p className="mt-0.5 text-[11px] text-emerald-700">
                    Today: {stepsToday.toLocaleString()} steps
                  </p>
                </div>

                <div className="rounded-2xl bg-white/90 p-3.5 ring-1 ring-sky-100/70">
                  <div className="flex items-center gap-1.5 text-xs font-semibold text-sky-700">
                    <Clock size={14} />
                    <span>Active Target</span>
                  </div>
                  <div className="mt-1 flex items-baseline gap-1">
                    <span className="text-lg font-bold text-gray-900">
                      {insight.recommendedActiveMinutes}
                    </span>
                    <span className="text-[11px] text-gray-400">mins/day</span>
                  </div>
                  <p className="mt-0.5 text-[11px] text-sky-700">
                    Today: {activeMinutesToday} mins
                  </p>
                </div>
              </div>

              {/* Highlights & Next Actions */}
              <div className="grid gap-3 sm:grid-cols-2">
                {insight.highlights.length > 0 && (
                  <div className="rounded-2xl bg-white/90 p-4 ring-1 ring-emerald-100/80">
                    <h5 className="mb-2.5 flex items-center gap-1.5 text-xs font-bold uppercase tracking-wider text-emerald-800">
                      <CheckCircle2 size={14} className="text-emerald-600" />
                      <span>What&apos;s Going Well</span>
                    </h5>
                    <ul className="space-y-2">
                      {insight.highlights.map((item, idx) => (
                        <li
                          key={idx}
                          className="flex items-start gap-2 text-xs leading-relaxed text-gray-700"
                        >
                          <span className="mt-1 h-1.5 w-1.5 shrink-0 rounded-full bg-emerald-500" />
                          <span>{item}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}

                {insight.nextActions.length > 0 && (
                  <div className="rounded-2xl bg-white/90 p-4 ring-1 ring-purple-100/80">
                    <h5 className="mb-2.5 flex items-center gap-1.5 text-xs font-bold uppercase tracking-wider text-purple-800">
                      <ArrowRight size={14} className="text-purple-600" />
                      <span>Recommended For Week {insight.pregnancyWeek}</span>
                    </h5>
                    <ul className="space-y-2">
                      {insight.nextActions.map((item, idx) => (
                        <li
                          key={idx}
                          className="flex items-start gap-2 text-xs leading-relaxed text-gray-700"
                        >
                          <span className="mt-1 h-1.5 w-1.5 shrink-0 rounded-full bg-purple-500" />
                          <span>{item}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}
              </div>

              {/* Stage Precautions */}
              {insight.precautions.length > 0 && (
                <div className="rounded-2xl bg-amber-50/70 px-4 py-3 ring-1 ring-amber-200/60">
                  <div className="mb-1.5 flex items-center gap-1.5 text-xs font-bold text-amber-900">
                    <ShieldAlert size={14} className="text-amber-600" />
                    <span>Gentle Stage Reminders</span>
                  </div>
                  <ul className="space-y-1">
                    {insight.precautions.map((item, idx) => (
                      <li key={idx} className="text-xs leading-relaxed text-amber-800">
                        • {item}
                      </li>
                    ))}
                  </ul>
                </div>
              )}
            </>
          ) : (
            <div className="rounded-2xl bg-white/80 p-5 text-center text-xs text-gray-500 ring-1 ring-purple-100">
              Click <strong>Refresh AI</strong> to generate your personalized pregnancy
              activity and health card.
            </div>
          )}
        </div>
      )}
    </div>
  );
}
